#  جلب توكن حساب واحد — timeout 20s
# ============================================================
async def fetch_one_token(session, uid, password, semaphore):
    """
    جلب توكن واحد مع timeout 20 ثانية.
    يستخدم semaphore للتحكم في التوازي.
    """
    url = JWT_API_TEMPLATE.format(uid=uid, password=password)
    timeout = aiohttp.ClientTimeout(total=TIMEOUT_PER_REQUEST)
    started = time.time()

    async with semaphore:
        try:
            async with session.get(url, timeout=timeout) as resp:
                elapsed = time.time() - started

                if resp.status != 200:
                    print(f"[{uid}] HTTP {resp.status} ({elapsed:.2f}s)")
                    return uid, None, None, None, f"http_{resp.status}"

                text = await resp.text()

                # ─── محاولة JSON ───
                try:
                    data = json.loads(text)
                    if isinstance(data, dict):
                        if data.get("ok") and data.get("token"):
                            print(f"[{uid}] ✅ OK ({elapsed:.2f}s) | "
                                  f"acc={data.get('account_id')} | "
                                  f"region={data.get('region')}")
                            return (
                                uid,
                                data["token"],
                                str(data.get("account_id", "")),
                                data.get("region", ""),
                                None
                            )
                        return uid, None, None, None, data.get("error", "not_ok")
                except json.JSONDecodeError:
                    pass

                # ─── fallback: نص مباشر ───
                token = text.strip()
                if len(token) > 20:
                    print(f"[{uid}] ✅ OK raw ({elapsed:.2f}s)")
                    return uid, token, None, None, None

                return uid, None, None, None, "empty_response"

        except asyncio.TimeoutError:
            print(f"[{uid}] ⏱ timeout after {TIMEOUT_PER_REQUEST}s")
            return uid, None, None, None, "timeout"
        except aiohttp.ClientError as e:
            print(f"[{uid}] ❌ connection error: {e}")
            return uid, None, None, None, f"conn_error"
        except Exception as e:
            print(f"[{uid}] ❌ {type(e).__name__}: {e}")
            return uid, None, None, None, "exception"


# ============================================================
#  جلب كل الحسابات — 5 في نفس الوقت فقط (بدون دفعات)
# ============================================================
async def fetch_all(accounts: dict, max_concurrent: int = 5):
    """
    يرسل كل الحسابات مرة واحدة لـ asyncio،
    لكن Semaphore(max_concurrent) يضمن تشغيل 5 فقط بالتوازي.
    الباقي ينتظرون دورهم تلقائياً (5 بـ 5) بدون دفعات.
    """
    total = len(accounts)
    print(f"\n{'='*60}")
    print(f"📊 Total accounts   : {total}")
    print(f"📊 Concurrent limit : {max_concurrent} (5 by 5)")
    print(f"📊 Timeout/req      : {TIMEOUT_PER_REQUEST}s")
    print(f"{'='*60}\n")

    semaphore = asyncio.Semaphore(max_concurrent)

    async with aiohttp.ClientSession() as session:
        tasks = [
            fetch_one_token(session, uid, password, semaphore)
            for uid, password in accounts.items()
        ]
        results = await asyncio.gather(*tasks, return_exceptions=True)

    # تجميع النتائج
    tokens = {}
    failed = []
    for result in results:
        if isinstance(result, Exception):
            failed.append(("unknown", str(result)))
            continue
        uid, token, acc_id, region, error = result
        if token:
            tokens[uid] = token
        else:
            failed.append((uid, error))

    print(f"\n{'='*60}")
    print(f"✅ ALL DONE: {len(tokens)}/{total} succeeded | {len(failed)} failed")
    print(f"{'='*60}\n")

    return tokens, failed


