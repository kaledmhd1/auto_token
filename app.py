TIMEOUT_PER_REQUEST = 10.0   # ← 10 ثوان لكل حساب
REQUEST_DELAY = 0.0          # ← تأخير بين كل طلب (اختياري)
CACHE_DURATION = 10000       # ← مدة الكاش بالثواني


